// A lista do usuário COLADA NUMA LINHA SÓ: todos os números devem ser identificados. Provedor interceptado (sem rede pública).
import fs from "node:fs";
import path from "node:path";
import { chromium } from "playwright";
const BASE = process.env.E2E_BASE || "http://localhost:4173/";
const OUT = path.resolve(process.env.E2E_SHOTS || "../docs/evidencias-chromium-2_4");
fs.mkdirSync(OUT, { recursive: true });
const res = {};
const ok = (k, v, d) => { res[k] = { ok: !!v, d }; console.log(`${v ? "PASSOU" : "FALHOU"} ${k}: ${d}`); };
const BLOB = "rua João eboli 53, avenida conselheiro nebias 78, rua doutor cochrane 197, rua tiro naval 8, avenida nebias 95, rua sete de setembro 35, rua cerquinho 21, rua são Paulo 94, rua doutor cesario Bastos 1, rua Antonio bento 278, rua antonio bento 234, rua silveira lobo 15, rua são Paulo 37, rua Joaquim Nabuco 5, rua general camara 85, rua professor Manuel de Abreu 117, rua capitão Adolfo Millon 12, rua pastor narciso de Andrade 42, rua silveira lobo 10, rua silveira lobo 20";
const b = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-unsafe-swiftshader"] });
const ctx = await b.newContext({ viewport: { width: 412, height: 915 }, serviceWorkers: "block", geolocation: { latitude: -23.9372, longitude: -46.3318, accuracy: 10 }, permissions: ["geolocation"] });
await ctx.addInitScript(() => { try { localStorage.setItem("rota.intro.skip", "1"); } catch {} });
const queries = [];
await ctx.route(/nominatim\.openstreetmap\.org/, (r) => {
  const u = new URL(r.request().url()); const st = (u.searchParams.get("street") || u.searchParams.get("q") || "").toLowerCase(); queries.push(st);
  const mk = (hn, lat, lon) => [{ lat: String(lat), lon: String(lon), display_name: "Rua Silveira Lobo, Santos", category: "place", type: "house", osm_type: "node", addresstype: "building", address: { road: "Rua Silveira Lobo", house_number: hn, city: "Santos", postcode: "11000-000" } }];
  const body = /^10 rua silveira lobo/.test(st) ? mk("10", -23.96, -46.33) : /^20 rua silveira lobo/.test(st) ? mk("20", -23.96, -46.329) : [];
  return r.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
});
const p = await ctx.newPage();
p.setDefaultTimeout(240000);
p.on("dialog", (d) => d.accept());
await p.goto(BASE);
await p.waitForSelector("[data-testid=map-home]");
await p.goto(BASE + "#/importar");
await p.getByRole("tab", { name: /Colar texto/ }).click();
await p.locator("#text").fill(BLOB);
await p.getByRole("button", { name: "Pré-visualizar" }).click();
await p.getByTestId("inferred").waitFor();
const t = await p.locator("main").innerText();
await p.screenshot({ path: path.join(OUT, "lista_previa.png") });
ok("prévia: 20 endereços separados de UMA linha", /Linhas lidas:\s*20/.test(t) && /Separei 20 endereços/.test(t), (t.match(/Separei[^\n]*/) || ["?"])[0]);
ok("prévia: 'Números identificados: 20 de 20'", /Números identificados:\s*20 de 20/.test(t), (t.match(/Números identificados:[^\n]*/) || ["?"])[0]);
await p.getByRole("button", { name: /Confirmar e localizar/ }).click();
await p.getByText(/consultados? no provedor online/).waitFor({ timeout: 280000 });
const st = await p.getByTestId("number-status").innerText();
await p.screenshot({ path: path.join(OUT, "lista_resultado.png") });
const nloc = +((st.match(/(\d+) localizado/) || [0, 0])[1]);
ok("resumo dos números: quase todos LOCALIZADOS pela base do IBGE (offline)", nloc >= 18, st.replace(/\n/g, " ").slice(0, 260));
const ib = await p.getByTestId("ibge-local").innerText().catch(() => "");
ok("aviso 'localizados offline pela base do IBGE'", /offline/.test(ib) && /IBGE/.test(ib), ib.slice(0, 160));
ok("a rede pública quase não é usada (só o que a base local não resolve)", queries.length <= 12, `${queries.length} consulta(s) ao provedor para 20 endereços`);
await p.goto(BASE + "#/");
await p.waitForSelector("[data-testid=map-home]");
const empty = await p.getByTestId("state-empty").count();
ok("mapa abre com os 20 imóveis (não vazio)", empty === 0, `state-empty=${empty}`);
await p.waitForTimeout(2500);
await p.getByRole("button", { name: "Calcular rota" }).click();
await p.waitForFunction(() => document.querySelector("[data-testid=map-home]")?.dataset.phase === "planned", null, { timeout: 240000 });
await p.waitForTimeout(3000);
await p.screenshot({ path: path.join(OUT, "lista_mapa.png") });
const counters = await p.getByTestId("counters").innerText().catch(() => "");
const guard = await p.getByTestId("route-guard").innerText().catch(() => "");
const nStops = +((counters.match(/(\d+) paradas/) || [0, 0])[1]);
ok("rota calculada com a lista: ≥ 18 paradas no mapa", nStops >= 18, counters.replace(/\n/g, " "));
ok("selo de segurança da rota presente (nada de 'Rota revisada' falso)", /Rota revisada|Destinos aproximados|Trechos não verificados/.test(guard), guard.replace(/\n/g, " | ").slice(0, 200));
fs.writeFileSync(path.join(OUT, "resultado_lista18.json"), JSON.stringify(res, null, 2));
await b.close();
const bad = Object.entries(res).filter(([, v]) => !v.ok).map(([k]) => k);
console.log(bad.length ? `FALHAS: ${bad.join("; ")}` : "TODOS PASSARAM");
process.exit(bad.length ? 1 : 0);
